#!/usr/bin/env python3
"""Generate the BoTorch reference fixtures used by the botorch_core parity tests.

Phase 1 (GP core, ``<out>/*.json``): the script builds a set of BoTorch
``SingleTaskGP`` models covering the features implemented in ``botorch_core``
(RBF / Matern-5/2 kernels, ScaleKernel, Normalize with learned or explicit
bounds, Standardize or no outcome transform, fixed noise, edge cases), sets
their hyperparameters explicitly and records:

* training data, transformed training data and transform statistics;
* default (initial) and explicitly set raw hyperparameters;
* kernel matrices and their autograd derivatives w.r.t. the raw hyperparameters;
* the exact MLL value and its autograd gradient (priors included);
* posteriors at test points (q = 1 batches and a joint q = 3 posterior, with
  and without observation noise) and their autograd derivatives w.r.t. X;
* the result of ``botorch.fit.fit_gpytorch_mll`` from the default
  initialization (final raw hyperparameters and loss, iterations, status), plus
  a finite-difference Hessian of the loss at the optimum to judge how well the
  optimum is determined.

Phase 2 (acquisition functions, ``<out>/phase2/*.json``): for fixed-hyperparameter
models, analytic acquisition values and autograd gradients (``maximize`` True and
False, several ``best_f`` / ``beta``), MC acquisition values and gradients
computed with explicitly recorded base samples (q = 1, 2, 3, with and without
pending points), qLogNoisyExpectedImprovement (incremental or not, full or
pruned baseline, and a check of ``cache_root=True`` against the plain
computation), ``prune_inferior_points`` with recorded base samples, values of the
synthetic test functions, and candidate generation on a fitted Hartmann-6 model
(``gen_candidates_scipy`` from fixed initial conditions and ``optimize_acqf``
over several seeds).

Phase 4 (``<out>/phase4/*.json``): multi-output and batched ``SingleTaskGP`` models
and ``ModelListGP`` models (fixed hyperparameters): per-element MLL values and
autograd gradients, joint posteriors over all outputs in BoTorch's layout (with
and without observation noise, batched inputs) and their derivatives with
respect to X, BoTorch's batched independent fits, and -- for unbatched models --
acquisition values and gradients with a ``ScalarizedPosteriorTransform``
(analytic, MC with explicit base samples, qLogNEI, ``prune_inferior_points``) and
of ``LogConstrainedExpectedImprovement`` / ``ConstrainedExpectedImprovement``.

Phase 4B (``<out>/phase4b/*.json``): for unbatched multi-output, single-output
and ``ModelListGP`` models, posterior samples from explicit multi-output base
samples, MC acquisition values and gradients with MC objectives (linear,
generic, constrained) and outcome constraints (qEI, qPI, qSR, qUCB, qLogEI,
qLogPF, qLogNEI with feasibility-weighted incumbents, including partly
infeasible baselines with recorded lower-bound points),
``prune_inferior_points`` with objectives and constraints and
``get_infeasible_cost``; constrained candidate generation
(``gen_candidates_scipy`` with SLSQP from fixed initial conditions and
``optimize_acqf`` over several seeds, linear / equality / inter-point /
nonlinear / fixed-feature constraints) and moments of hit-and-run polytope
samples.

Phase 5A, utilities (``<out>/phase5a_utils/*.json``): the multi-objective
utilities -- ``is_non_dominated`` (all flags, batches, BoTorch's loop variant,
infinities; NaN outcomes in ``pareto_nan.json``, written only with a BoTorch
that includes meta-pytorch/botorch#3392), ``Hypervolume``,
``infer_reference_point``, ``get_hypervolume_maximizing_subset`` (with
BoTorch's random choices), the three box decompositions (states after
construction, incremental updates and ``reset``, batches), the helpers of
``box_decompositions.utils``, ``get_chebyshev_scalarization`` (values and
gradients) and the transformations of ``sample_simplex`` and
``sample_hypersphere``.

Phase 5A-TF (``--phase 5a-tf``, ``<out>/phase5a_tf/*.json``, generated by
``scripts/fixtures_mo_test_functions.py``):
BoTorch's multi-objective test problems (values, constraint slacks, reference
points, maximum hypervolumes, Pareto fronts) and the samplers of the DTLZ fronts.

Phase 5B (``--phase 5b``, ``<out>/phase5b/*.json``, generated by
``scripts/fixtures_mo_acquisition.py``): the multi-objective acquisition
functions (qEHVI, qLogEHVI, qNEHVI, qLogNEHVI, analytic EHVI, qLogNParEGO),
the multi-output objectives and ``prune_inferior_points_multi_objective``.
``--phase 5b-3392`` writes ``phase5b/pending_3392.json`` and needs a BoTorch
that includes meta-pytorch/botorch#3392 (cached pending points); it is not
part of ``all``.

Phase 5C-HVKG (``--phase 5c-hvkg``, ``<out>/phase5c_hvkg/*.json``, generated by
``scripts/fixtures_mo_hvkg.py``): conditioning on observations and fantasy
models, cost models and cost-aware utilities, and the hypervolume knowledge
gradient (values, gradients, value functions, ``optimize_acqf`` and the
one-shot initial conditions). ``--phase 5c-hvkg-prs`` writes the cases that
need meta-pytorch/botorch#3396 or #3399; it is not part of ``all``.

Phase 5C-entropy (``--phase 5c-entropy``, ``<out>/phase5c_entropy/*.json``,
generated by ``scripts/fixtures_mo_entropy.py``): pathwise sampling, the
sampled Pareto sets and their box decompositions, and the multi-objective
max-value, joint and predictive entropy search acquisition functions.

Phase 5C-robust (``--phase 5c-robust``, ``<out>/phase5c_robust/*.json``,
generated by ``scripts/fixtures_mo_robust.py``): ``InputPerturbation`` and
models with it, the (multi-output) risk measures, the multi-objective
acquisition functions with risk-measure objectives, ``MARS`` with qLogNEI,
``MOMF`` and the deterministic parts of NSGA-II. ``--phase 5c-robust-3392``
writes ``phase5c_robust/risk_measures_3392.json`` (MVaR with ties) and needs a
BoTorch with meta-pytorch/botorch#3392; it is not part of ``all``.

Usage (from the repository root, with BoTorch, GPyTorch and PyTorch installed)::

    python scripts/generate_fixtures.py [--out botorch_core/tests/fixtures] [--phase 1|2|4|4b|5a-utils|5a-tf|5b|5b-3392|5c-hvkg|5c-hvkg-prs|5c-entropy|5c-robust|5c-robust-3392|all]

To use a source checkout of BoTorch, put it first on the path, e.g.
``PYTHONPATH=/path/to/botorch python -P scripts/generate_fixtures.py``.

The output is deterministic (fixed seeds, float64 everywhere, single thread).
Each case is written to ``<out>/<name>.json``.
"""

